<?php

declare(strict_types=1);

namespace App\Actions\Music;

use App\Models\Play;
use App\Models\Setting;
use App\Models\SpotifyPlaylist;
use App\Services\Spotify\SpotifyPlaylistService;
use Illuminate\Support\Carbon;
use RuntimeException;

final class CreateSpotifyPlaylist
{
    public function __construct(
        private readonly SpotifyPlaylistService $playlistService,
    ) {}

    public function handle(
        string $periodType,
        int $trackLimit,
        string $playlistName,
        ?int $year = null,
        ?string $from = null,
        ?string $to = null,
    ): array {
        [$start, $end] = $this->resolveDateRange($periodType, $year, $from, $to);

        $topPlays = Play::selectRaw('track_id, COUNT(*) as play_count')
            ->whereBetween('played_at', [$start, $end])
            ->groupBy('track_id')
            ->orderByDesc('play_count')
            ->limit($trackLimit)
            ->with('track:id,spotify_uri')
            ->get();

        $uris = $topPlays
            ->map(fn ($p) => $p->track?->spotify_uri)
            ->filter()
            ->values()
            ->all();

        if (empty($uris)) {
            throw new RuntimeException('No tracks found for the selected period.');
        }

        $userId = Setting::get('spotify_id');
        if (! $userId) {
            throw new RuntimeException('Spotify user ID not found. Please reconnect Spotify.');
        }

        $description = $this->buildDescription($periodType, $year, $from, $to, count($uris));

        $playlistId = $this->playlistService->create($userId, $playlistName, $description);
        $this->playlistService->addTracks($playlistId, $uris);

        $url = $this->playlistService->getUrl($playlistId);

        $playlist = SpotifyPlaylist::create([
            'spotify_playlist_id' => $playlistId,
            'name' => $playlistName,
            'period_type' => $periodType,
            'period_from' => $start->toDateString(),
            'period_to' => $end->toDateString(),
            'track_count' => count($uris),
            'url' => $url,
        ]);

        $pivotData = [];
        foreach ($topPlays->filter(fn ($p) => $p->track?->spotify_uri !== null) as $position => $play) {
            $pivotData[$play->track_id] = [
                'play_count' => (int) $play->play_count,
                'position' => $position,
            ];
        }
        $playlist->tracks()->attach($pivotData);

        return [
            'url' => $url,
            'name' => $playlistName,
            'track_count' => count($uris),
        ];
    }

    /** @return array{Carbon, Carbon} */
    private function resolveDateRange(string $periodType, ?int $year, ?string $from, ?string $to): array
    {
        return match ($periodType) {
            'last_30_days' => [now()->subDays(30)->startOfDay(),                now()->endOfDay()],
            'last_6_months' => [now()->subMonths(6)->startOfDay(),               now()->endOfDay()],
            'this_year' => [now()->startOfYear(),                            now()->endOfDay()],
            'specific_year' => [Carbon::create($year)->startOfYear(),            Carbon::create($year)->endOfYear()],
            'custom' => [Carbon::parse($from)->startOfDay(),              Carbon::parse($to)->endOfDay()],
            default => throw new RuntimeException("Unknown period type: {$periodType}"),
        };
    }

    private function buildDescription(string $periodType, ?int $year, ?string $from, ?string $to, int $count): string
    {
        $period = match ($periodType) {
            'last_30_days' => 'last 30 days',
            'last_6_months' => 'last 6 months',
            'this_year' => (string) now()->year,
            'specific_year' => (string) $year,
            'custom' => Carbon::parse($from)->format('M j, Y').' – '.Carbon::parse($to)->format('M j, Y'),
            default => 'custom period',
        };

        return "Top {$count} most played tracks — {$period}. Generated by Pulse.";
    }
}
